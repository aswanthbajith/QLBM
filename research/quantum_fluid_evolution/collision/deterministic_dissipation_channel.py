"""Deterministic Dissipation Quantum Channel for Lattice Boltzmann Collision.

Based on:
  Khan, Succi, Yao (2026), "Deterministic Realization of Classical Dissipation on
  Quantum Computers", arXiv:2604.25429.

Eliminates the multiplicative postselection decay of block-encoding by realizing
dissipative collision via signed two-rail encoding and Completely Positive Trace-
Preserving (CPTP) quantum channels.

Key Mathematical Principles:
-----------------------------
1. Signed Two-Rail Encoding:
   Real population perturbations delta in [-delta_max, delta_max] are mapped to
   a normalized single-qubit density matrix:
     p_+ = (delta_max + delta) / (2 * delta_max)
     p_- = (delta_max - delta) / (2 * delta_max)
   such that Tr(rho) = p_+ + p_- = 1.0 and rho_{00} - rho_{11} = delta / delta_max.

2. CPTP Contraction Channel:
   For relaxation factor lambda = 1 - 1/tau in [-1, 1], the contractive channel
   is generated by the two Kraus operators:
     q_0 = (1 + lambda) / 2,   q_1 = (1 - lambda) / 2
     K_0 = sqrt(q_0) * I_2,    K_1 = sqrt(q_1) * X
   
   Completeness Relation:
     K_0^dag K_0 + K_1^dag K_1 = (q_0 + q_1) * I_2 = I_2
   
   Action on Density Matrix:
     E(rho) = K_0 rho K_0^dag + K_1 rho K_1^dag
     Tr(E(rho)) == 1.0 (Exact, Deterministic, Zero Shot Overhead)
     delta_out = delta_max * (E(rho)_{00} - E(rho)_{11}) = lambda * delta
"""

